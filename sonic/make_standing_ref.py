"""Write a neutral standing reference motion for g1_deploy_onnx_ref (reference/standing/stand_000).

Why: on every switch into planner mode the deploy parks the policy on frame 0 of the first loaded reference motion for
at least 100 ms (zmq_manager.hpp polls the planner init every 100 ms); with reference/example/ that motion is
dance_in_da_party (joint speeds to 16 rad/s in its first second), and the robot lunges 0.7-0.9 m and falls (57 of 94
boot-stage falls over 1132 boots, FAILURE_LOG row 167). This motion is SONIC's default standing pose, upright,
heading-aligned, 500 identical frames, zero velocities. Run inside the sim container (numpy only):
    PYTHONPATH=<rax> python make_standing_ref.py [out_dir]
"""
import os, sys
import numpy as np

RAX = "/home/junjieye/workspace/multirobot/2/homebody/.cache/rax-g1real"
sys.path.insert(0, RAX)
from services.g1sonic import robot as R  # noqa: E402

DEPLOY = "/opt/sonic/gear_sonic_deploy"
TEMPLATE = f"{DEPLOY}/reference/example/squat_001__A359"
OUT = sys.argv[1] if len(sys.argv) > 1 else f"{DEPLOY}/reference/standing/stand_000"
N = 500


def q_mul(a, b):
    w1, x1, y1, z1 = a; w2, x2, y2, z2 = b
    return np.array([w1*w2 - x1*x2 - y1*y2 - z1*z2, w1*x2 + x1*w2 + y1*z2 - z1*y2,
                     w1*y2 - x1*z2 + y1*w2 + z1*x2, w1*z2 + x1*y2 - y1*x2 + z1*w2])


def q_rot(q, v):
    w, x, y, z = q
    u = np.array([x, y, z])
    return v + 2 * np.cross(u, np.cross(u, v) + w * v)


def load(name):
    return np.loadtxt(f"{TEMPLATE}/{name}.csv", delimiter=",", skiprows=1)


def header(name):
    return open(f"{TEMPLATE}/{name}.csv").readline().strip()


bp, bq = load("body_pos")[0].reshape(14, 3), load("body_quat")[0].reshape(14, 4)
# heading-align the template frame: rotate every body by the inverse of the root yaw, put the root at x = y = 0
w, x, y, z = bq[0]
yaw = np.arctan2(2 * (w * z + x * y), 1 - 2 * (y * y + z * z))
inv = np.array([np.cos(-yaw / 2), 0.0, 0.0, np.sin(-yaw / 2)])
root_xy = bp[0, :2].copy()
for i in range(14):
    bp[i] = q_rot(inv, bp[i] - np.array([root_xy[0], root_xy[1], 0.0]))
    bq[i] = q_mul(inv, bq[i])
bq[0] = np.array([1.0, 0.0, 0.0, 0.0])  # the anchor (root) exactly upright
joints = np.asarray(R.DEFAULT_STANDING, dtype=float)  # IsaacLab order, as the motion files
assert joints.shape == (29,)

os.makedirs(OUT, exist_ok=True)
def write(name, row):
    rows = np.tile(np.asarray(row, dtype=float).reshape(1, -1), (N, 1))
    np.savetxt(f"{OUT}/{name}.csv", rows, delimiter=",", fmt="%.6f", header=header(name), comments="")
write("joint_pos", joints)
write("joint_vel", np.zeros(29))
write("body_pos", bp.reshape(-1))
write("body_quat", bq.reshape(-1))
write("body_lin_vel", np.zeros(42))
write("body_ang_vel", np.zeros(42))
indexes = open(f"{TEMPLATE}/metadata.txt").read().split("Body part indexes:")[1].splitlines()[1].strip()
open(f"{OUT}/metadata.txt", "w").write(
    f"Metadata for: stand_000\n==============================\n\nBody part indexes:\n{indexes}\n\nTotal timesteps: {N}\n\n"
    "Data arrays summary:\n  joint_pos: (500, 29) (float32)\n  joint_vel: (500, 29) (float32)\n  body_pos_w: (500, 14, 3) (float32)\n"
    "  body_quat_w: (500, 14, 4) (float32)\n  body_lin_vel_w: (500, 14, 3) (float32)\n  body_ang_vel_w: (500, 14, 3) (float32)\n")
open(f"{OUT}/info.txt", "w").write("Motion Information: stand_000\nSONIC default standing pose, upright, heading-aligned, "
                                   f"{N} identical frames (10 s), zero velocities. Generated by 3/eng/make_standing_ref.py\n")
print("wrote", OUT, "root", bp[0].round(3), "root quat", bq[0], "joints(mujoco order)",
      np.round(R.to_mujoco(joints), 3)[:6])
